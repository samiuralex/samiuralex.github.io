// Parallax effect for hero section (disabled on small screens)
function handleParallax() {
    const hero = document.querySelector('.hero');
    if (!hero) return;
    if (window.innerWidth < 768) {
        hero.style.transform = 'none';
        window.removeEventListener('scroll', parallaxScroll);
        return;
    }
    window.addEventListener('scroll', parallaxScroll);
}

function parallaxScroll() {
    const scrolled = window.pageYOffset;
    const hero = document.querySelector('.hero');
    if (!hero) return;
    const rate = scrolled * -0.2; // subtle
    hero.style.transform = `translateY(${rate}px)`;
}

// Keep parallax subtle and opt-in only on larger screens
window.addEventListener('load', handleParallax);
window.addEventListener('resize', handleParallax);

// Add hover effects to cards
document.querySelectorAll('.timeline-content, .education-card, .cert-card, .activity-card').forEach(card => {
    card.addEventListener('mouseenter', () => {
        card.style.transform = 'translateY(-5px)';
        card.style.boxShadow = '0 10px 25px rgba(0, 0, 0, 0.1)';
    });
    
    card.addEventListener('mouseleave', () => {
        card.style.transform = 'translateY(0)';
        card.style.boxShadow = '0 4px 6px rgba(0, 0, 0, 0.05)';
    });
});

// Add click animation to buttons
document.querySelectorAll('.btn').forEach(btn => {
    btn.addEventListener('click', function(e) {
        const ripple = document.createElement('span');
        const rect = this.getBoundingClientRect();
        const size = Math.max(rect.width, rect.height);
        const x = e.clientX - rect.left - size / 2;
        const y = e.clientY - rect.top - size / 2;
        
        ripple.style.width = ripple.style.height = size + 'px';
        ripple.style.left = x + 'px';
        ripple.style.top = y + 'px';
        ripple.classList.add('ripple');
        
        this.appendChild(ripple);
        
        setTimeout(() => {
            ripple.remove();
        }, 600);
    });
});

